"""Pruning Class icon (design `appIcon`): one set of shapes drawn three ways, so they always match: the adaptive-icon
foreground vector (`res/drawable/ic_launcher_foreground.xml`), the legacy launcher PNG and the 512 export for the factory
gallery.

    python tools/make_icon.py <export-512.png>

Sprout yellow-green tile #8A9A2B; a white flat line branch rising to the upper right with three small buds (the top one,
facing out, purple-red #9C2F4A), a short slanted cut line above its tip, and an open pair of pruning shears at the lower
right. No text, no gradient. Coordinates are the vector's 108-unit viewport (safe zone 21..87).
"""
import math
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
GREEN = (0x8A, 0x9A, 0x2B, 255)
WHITE = (255, 255, 255, 255)
BUD = (0x9C, 0x2F, 0x4A, 255)

STROKE = 4.2
BRANCH = [(27, 80), (40, 62), (52, 46), (61, 33)]
CUT = [(56, 25), (70, 31)]
# shears: two blades crossing at the pivot, handles as loops
PIVOT = (70, 68)
BLADES = [[(PIVOT[0] - 9, PIVOT[1] - 12), (PIVOT[0] + 6, PIVOT[1] + 7)], [(PIVOT[0] + 4, PIVOT[1] - 14), (PIVOT[0] - 6, PIVOT[1] + 7)]]
LOOPS = [(PIVOT[0] + 9, PIVOT[1] + 11, 4.2), (PIVOT[0] - 9, PIVOT[1] + 11, 4.2)]


def bud(at, along, size, outward):
    """A small pointed bud on the branch at [at], leaning along the branch and to the [outward] side."""
    ax, ay = along
    nx, ny = -ay, ax
    if outward < 0:
        nx, ny = -nx, -ny
    tip = (at[0] + (nx * 0.9 + ax * 0.6) * size, at[1] + (ny * 0.9 + ay * 0.6) * size)
    b1 = (at[0] + ax * size * 0.45, at[1] + ay * size * 0.45)
    b2 = (at[0] - ax * size * 0.45, at[1] - ay * size * 0.45)
    return [b1, tip, b2]


def shapes():
    ax, ay = BRANCH[-1][0] - BRANCH[0][0], BRANCH[-1][1] - BRANCH[0][1]
    l = math.hypot(ax, ay)
    along = (ax / l, ay / l)
    def on(t):
        return (BRANCH[0][0] + ax * t, BRANCH[0][1] + ay * t)
    buds = [(bud(on(0.30), along, 7, -1), WHITE), (bud(on(0.56), along, 7, 1), WHITE), (bud(on(0.82), along, 9, 1), BUD)]
    return buds


def vector():
    def fmt(v):
        return f"{v:.2f}".rstrip("0").rstrip(".")

    def stroke(pts, w=STROKE):
        d = "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts)
        return (
            f'    <path\n        android:pathData="{d}"\n        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="{w}"\n'
            '        android:strokeLineCap="round"\n        android:strokeLineJoin="round"\n        android:fillColor="#00000000" />\n'
        )

    def circle(cx, cy, r, w):
        return (
            f'    <path\n        android:pathData="M{fmt(cx - r)},{fmt(cy)}a{fmt(r)},{fmt(r)} 0,1 1,{fmt(2 * r)},0a{fmt(r)},{fmt(r)} 0,1 1,{fmt(-2 * r)},0z"\n'
            f'        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="{w}"\n        android:fillColor="#00000000" />\n'
        )

    out = [
        '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- Pruning Class: white branch with buds (top one purple-red, facing out), a slanted cut line, open shears "
        "(design appIcon); generated by tools/make_icon.py -->\n",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n',
    ]
    out.append(stroke(BRANCH))
    out.append(stroke(CUT, 3.2))
    for b in BLADES:
        out.append(stroke(b, 3.6))
    for cx, cy, r in LOOPS:
        out.append(circle(cx, cy, r, 3.0))
    for pts, color in shapes():
        hexc = "#FF%02X%02X%02X" % color[:3]
        d = "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts) + "Z"
        out.append(f'    <path\n        android:pathData="{d}"\n        android:fillColor="{hexc}" />\n')
    out.append("</vector>\n")
    return "".join(out)


def raster(size, rounded):
    k = 8
    S = size * k
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.22), fill=GREEN)
    else:
        d.rectangle([0, 0, S, S], fill=GREEN)
    u = S / 108.0

    def line(pts, w):
        d.line([(x * u, y * u) for x, y in pts], fill=WHITE, width=int(w * u), joint="curve")
        for x, y in (pts[0], pts[-1]):
            rr = w * u / 2
            d.ellipse([x * u - rr, y * u - rr, x * u + rr, y * u + rr], fill=WHITE)

    line(BRANCH, STROKE)
    line(CUT, 3.2)
    for b in BLADES:
        line(b, 3.6)
    for cx, cy, r in LOOPS:
        d.ellipse([(cx - r) * u, (cy - r) * u, (cx + r) * u, (cy + r) * u], outline=WHITE, width=int(3.0 * u))
    for pts, color in shapes():
        d.polygon([(x * u, y * u) for x, y in pts], fill=color)
    return img.resize((size, size), Image.LANCZOS)


def main():
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
        f.write(vector())
    raster(192, rounded=False).save(os.path.join(RES, "mipmap-xxxhdpi", "ic_launcher.png"))
    if len(sys.argv) > 1:
        raster(512, rounded=True).save(sys.argv[1])
        print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()
